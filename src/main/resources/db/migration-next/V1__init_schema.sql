CREATE TABLE calendar_feed_tokens (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_id  BIGINT      NOT NULL REFERENCES calendars (id) ON DELETE CASCADE,
    token        UUID        NOT NULL DEFAULT gen_random_uuid(),
    visibility   VARCHAR(16) NOT NULL DEFAULT 'FULL',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at TIMESTAMPTZ,
    revoked_at   TIMESTAMPTZ,
    CONSTRAINT calendar_feed_tokens_uq UNIQUE (token),
    CONSTRAINT calendar_feed_tokens_visibility_chk CHECK (visibility IN ('FULL', 'BUSY_ONLY'))
);

CREATE INDEX calendar_feed_tokens_calendar_idx
    ON calendar_feed_tokens (calendar_id) WHERE revoked_at IS NULL;
